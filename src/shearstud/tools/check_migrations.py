"""Applied migrations are frozen, and the lock file is what says so.

``migrations.lock`` carries one line per migration: version, name and the digest
of the statements. A migration that has run against any book anywhere is never
edited, so a digest that has moved means somebody edited a migration instead of
adding one, and every book already upgraded is now running a schema the code
cannot describe.

The lock is checked rather than regenerated by this command. Regenerating it is
``build_lock``, and keeping the two apart is the point: a check that fixed what
it found would make the fix invisible in the diff.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Final

from shearstud.errors import ConfigError
from shearstud.store import migrate
from shearstud.tools.walk import REPO_ROOT, report

#: Where the lock lives.
LOCK_PATH: Final[Path] = REPO_ROOT / "migrations.lock"

#: How a lock line is written.
LINE_FIELDS: Final[int] = 3


@dataclass(frozen=True, slots=True)
class LockLine:
    """One migration as the lock records it."""

    version: int
    name: str
    digest: str


def parse_lock(text: str) -> list[LockLine]:
    """Read the lock file's lines, comments and blanks dropped."""
    out: list[LockLine] = []
    for number, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != LINE_FIELDS:
            raise ConfigError(f"{LOCK_PATH.name} line {number}: expected version, name, digest")
        try:
            version = int(parts[0])
        except ValueError:
            raise ConfigError(
                f"{LOCK_PATH.name} line {number}: {parts[0]!r} is not a version"
            ) from None
        out.append(LockLine(version=version, name=parts[1], digest=parts[2]))
    return out


def read_lock(path: Path | None = None) -> list[LockLine]:
    """The lock file as it is on disk."""
    target = path or LOCK_PATH
    if not target.exists():
        raise ConfigError(f"no {target.name} at {target}")
    return parse_lock(target.read_text(encoding="utf-8"))


def expected_lines() -> list[LockLine]:
    """What the lock should say, from the migrations in the code."""
    return [
        LockLine(
            version=int(module.VERSION),
            name=str(module.NAME),
            digest=migrate.digest_of(module),
        )
        for module in migrate.available()
    ]


def problems(path: Path | None = None) -> list[str]:
    """Every way the lock and the migrations disagree."""
    target = path or LOCK_PATH
    if not target.exists():
        return [f"no {target.name} at {target}"]
    locked = {line.version: line for line in read_lock(target)}
    expected = expected_lines()
    found: list[str] = []
    for line in expected:
        recorded = locked.get(line.version)
        if recorded is None:
            found.append(f"migration {line.version} ({line.name}) is not in the lock")
            continue
        if recorded.name != line.name:
            found.append(
                f"migration {line.version} is {line.name!r} in the code and "
                f"{recorded.name!r} in the lock"
            )
        if recorded.digest != line.digest:
            found.append(
                f"migration {line.version} ({line.name}) has been edited since it was locked"
            )
    known = {line.version for line in expected}
    for version in sorted(set(locked) - known):
        found.append(f"the lock has migration {version} and the code does not")
    return found


def lock_text() -> str:
    """What the lock file should contain, for ``build_lock`` to write."""
    head = [
        "# Digests of every applied migration. Frozen: a migration that has run",
        "# anywhere is never edited, and check_migrations fails the build if one is.",
        "# Regenerate with: python -m shearstud.tools.build_lock",
    ]
    body = [f"{line.version:03d} {line.name} {line.digest}" for line in expected_lines()]
    return "\n".join([*head, *body]) + "\n"


def main() -> int:
    """Run the check and report."""
    return report("check_migrations", problems())


if __name__ == "__main__":  # pragma: no cover
    sys.exit(main())
