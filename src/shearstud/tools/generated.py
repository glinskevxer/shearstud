"""The write-or-check contract every generated document follows.

Each generator builds its text from the code and hands it here. Running the
generator writes the file; running it with ``--check`` compares and changes
nothing, which is the form CI uses.

The two have to be the same code path or the check drifts from the write, and a
drifted check is worse than none: it passes on a file the generator would have
written differently, so the document in the repository stops describing the
code and nothing says so.

Every document opens with a line saying it is generated and which command wrote
it. That line is part of the compared text, so a hand edit that removes the
warning fails the check along with everything else.
"""

from __future__ import annotations

import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Final

from shearstud.tools.walk import REPO_ROOT

#: Where generated documents live.
DOCS_ROOT: Final[Path] = REPO_ROOT / "docs"

#: The warning every generated document opens with.
BANNER: Final[str] = "<!-- Generated by {command}. Do not edit by hand. -->"


@dataclass(frozen=True, slots=True)
class Document:
    """One generated document: where it goes and what wrote it."""

    filename: str
    command: str

    @property
    def path(self) -> Path:
        """Where the document is written."""
        return DOCS_ROOT / self.filename

    def wrap(self, body: str) -> str:
        """The banner, the body, and exactly one trailing newline."""
        return BANNER.format(command=self.command) + "\n\n" + body.rstrip("\n") + "\n"

    def is_current(self, body: str) -> bool:
        """Whether the file on disk already says this."""
        if not self.path.exists():
            return False
        return self.path.read_text(encoding="utf-8") == self.wrap(body)

    def write(self, body: str) -> bool:
        """Write the document, returning whether anything changed."""
        if self.is_current(body):
            return False
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.path.write_text(self.wrap(body), encoding="utf-8", newline="\n")
        return True


def run(document: Document, body: str, argv: list[str] | None = None) -> int:
    """Write or check one document, the way every generator's main does."""
    args = sys.argv[1:] if argv is None else argv
    if "--check" in args:
        if document.is_current(body):
            print(f"{document.command}: {document.filename} is current")
            return 0
        print(f"{document.command}: {document.filename} is out of date")
        return 1
    changed = document.write(body)
    print(f"{document.command}: {'rewrote' if changed else 'left'} {document.filename}")
    return 0


def table(headings: list[str], rows: list[list[str]]) -> str:
    """A markdown table with its columns padded to line up in the source.

    Padding costs nothing to read rendered and makes the raw file legible in a
    diff, which is where these documents are actually read.
    """
    if not rows:
        return ""
    widths = [len(head) for head in headings]
    for row in rows:
        for index, cell in enumerate(row):
            widths[index] = max(widths[index], len(cell))
    lines = [
        "| " + " | ".join(head.ljust(widths[i]) for i, head in enumerate(headings)) + " |",
        "| " + " | ".join("-" * widths[i] for i in range(len(headings))) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(cell.ljust(widths[i]) for i, cell in enumerate(row)) + " |")
    return "\n".join(lines)
