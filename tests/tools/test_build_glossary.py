"""The glossary, and the contract every generated document shares."""

from __future__ import annotations

import pytest

from shearstud.tools import build_glossary as build

pytestmark = pytest.mark.tools


def test_the_shipped_document_is_current() -> None:
    assert build.DOCUMENT.is_current(build.body())


def test_the_check_exits_zero_when_the_document_is_current() -> None:
    assert build.main(["--check"]) == 0


def test_the_document_opens_with_the_generated_banner() -> None:
    text = build.DOCUMENT.wrap(build.body())
    assert text.splitlines()[0].startswith("<!-- Generated by build_glossary")


def test_the_banner_names_the_command_that_wrote_it() -> None:
    assert "build_glossary" in build.DOCUMENT.wrap("body")


def test_the_document_ends_in_exactly_one_newline() -> None:
    text = build.DOCUMENT.wrap("body\n\n\n")
    assert text.endswith("body\n")
    assert not text.endswith("\n\n")


def test_every_unit_suffix_appears() -> None:
    from shearstud.units import SUFFIXES

    text = build.body()
    for suffix in SUFFIXES:
        assert f"`_{suffix}`" in text


def test_every_detail_category_appears() -> None:
    from shearstud.fatigue import categories as cat

    text = build.body()
    for name in cat.NAMES:
        assert name in text


def test_every_vehicle_appears() -> None:
    from shearstud.loads import vehicles

    text = build.body()
    for name in vehicles.names():
        assert name in text


def test_the_category_rows_carry_the_published_thresholds() -> None:
    rows = {row[0]: row for row in build.category_rows()}
    assert rows["E'"][2] == "2.6"
    assert rows["A"][2] == "24"


def test_the_vehicle_rows_carry_the_gross_weights() -> None:
    rows = {row[0]: row for row in build.vehicle_rows()}
    assert rows["TYPE3S2"][3] == "72"
    assert rows["EV3"][3] == "86"


def test_the_vehicle_rows_are_grouped_by_class() -> None:
    classes = [row[1] for row in build.vehicle_rows()]
    assert classes == sorted(classes)


def test_the_unit_rows_are_sorted_by_the_suffix_itself() -> None:
    # Sorted on the bare suffix, not on the rendered cell: the backticks put
    # `_in2` ahead of `_in` and that is not the order anybody reads it in.
    suffixes = [row[0].strip("`_") for row in build.unit_rows()]
    assert suffixes == sorted(suffixes)
