"""The write-or-check contract every generated document shares."""

from __future__ import annotations

from pathlib import Path

import pytest

from shearstud.tools import generated
from shearstud.tools.generated import Document, table

pytestmark = pytest.mark.tools


@pytest.fixture
def docs(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    monkeypatch.setattr(generated, "DOCS_ROOT", tmp_path)
    return tmp_path


def test_the_docs_root_is_beside_the_repository() -> None:
    assert generated.DOCS_ROOT.name == "docs"


def test_a_document_knows_where_it_goes(docs: Path) -> None:
    assert Document("x.md", "build_x").path == docs / "x.md"


def test_the_banner_names_the_command() -> None:
    text = Document("x.md", "build_x").wrap("body")
    assert text.splitlines()[0] == "<!-- Generated by build_x. Do not edit by hand. -->"


def test_the_banner_is_followed_by_a_blank_line() -> None:
    text = Document("x.md", "build_x").wrap("body")
    assert text.splitlines()[1] == ""


def test_the_wrapped_text_ends_in_exactly_one_newline() -> None:
    text = Document("x.md", "build_x").wrap("body\n\n\n")
    assert text.endswith("body\n")
    assert not text.endswith("\n\n")


def test_a_document_that_is_not_there_is_not_current(docs: Path) -> None:
    assert not Document("missing.md", "build_missing").is_current("body")


def test_writing_creates_the_file(docs: Path) -> None:
    document = Document("new.md", "build_new")
    assert document.write("body") is True
    assert document.path.exists()


def test_writing_the_same_body_twice_changes_nothing(docs: Path) -> None:
    document = Document("new.md", "build_new")
    document.write("body")
    assert document.write("body") is False


def test_a_written_document_is_current(docs: Path) -> None:
    document = Document("new.md", "build_new")
    document.write("body")
    assert document.is_current("body")


def test_a_changed_body_is_not_current(docs: Path) -> None:
    document = Document("new.md", "build_new")
    document.write("old")
    assert not document.is_current("new")


def test_removing_the_banner_makes_the_document_stale(docs: Path) -> None:
    document = Document("new.md", "build_new")
    document.write("body")
    document.path.write_text("body\n", encoding="utf-8")
    assert not document.is_current("body")


def test_writing_makes_the_directory(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(generated, "DOCS_ROOT", tmp_path / "deep" / "down")
    document = Document("new.md", "build_new")
    assert document.write("body") is True
    assert document.path.exists()


def test_the_runner_writes_by_default(docs: Path, capsys: pytest.CaptureFixture[str]) -> None:
    document = Document("new.md", "build_new")
    assert generated.run(document, "body", []) == 0
    assert "rewrote new.md" in capsys.readouterr().out


def test_the_runner_says_when_it_left_the_file_alone(
    docs: Path, capsys: pytest.CaptureFixture[str]
) -> None:
    document = Document("new.md", "build_new")
    generated.run(document, "body", [])
    capsys.readouterr()
    generated.run(document, "body", [])
    assert "left new.md" in capsys.readouterr().out


def test_the_runner_passes_a_current_check(docs: Path, capsys: pytest.CaptureFixture[str]) -> None:
    document = Document("new.md", "build_new")
    document.write("body")
    assert generated.run(document, "body", ["--check"]) == 0
    assert "is current" in capsys.readouterr().out


def test_the_runner_fails_a_stale_check(docs: Path, capsys: pytest.CaptureFixture[str]) -> None:
    document = Document("new.md", "build_new")
    document.write("old")
    assert generated.run(document, "new", ["--check"]) == 1
    assert "out of date" in capsys.readouterr().out


def test_a_check_never_writes(docs: Path) -> None:
    document = Document("new.md", "build_new")
    document.write("old")
    generated.run(document, "new", ["--check"])
    assert document.path.read_text(encoding="utf-8") == document.wrap("old")


def test_a_table_lines_its_columns_up() -> None:
    text = table(["a", "bbbb"], [["cccc", "d"]])
    widths = {len(line) for line in text.splitlines()}
    assert len(widths) == 1


def test_a_table_with_no_rows_is_empty() -> None:
    assert table(["a", "b"], []) == ""


def test_a_table_carries_a_separator_row() -> None:
    text = table(["a", "b"], [["c", "d"]])
    assert set(text.splitlines()[1]) <= {"|", "-", " "}


def test_a_table_keeps_every_row() -> None:
    text = table(["a"], [["one"], ["two"], ["three"]])
    assert len(text.splitlines()) == 5
